"""Customer uploads (logos, artwork). Local disk for now; S3-compatible object storage (step 7) implements
the same FileStore interface.

The type is decided from the file's first bytes, never from its name or the browser's claim.
"""

import uuid
from pathlib import Path
from typing import Optional, Protocol

MAX_BYTES = 10 * 1024 * 1024
MAX_FILES_PER_ORDER = 10

# content type -> extension, for the formats factories ask for
ALLOWED = {
    "image/png": "png", "image/jpeg": "jpg", "image/webp": "webp", "image/svg+xml": "svg",
    "application/pdf": "pdf", "application/postscript": "eps",
}
IMAGE_TYPES = {"image/png", "image/jpeg", "image/webp", "image/svg+xml"}


def sniff_type(data: bytes) -> Optional[str]:
    """Content type from magic bytes; None if it is not an allowed format.
    Adobe Illustrator (.ai) files are PDF or PostScript inside, so they pass as one of those."""
    head = data[:1024]
    if head.startswith(b"\x89PNG\r\n\x1a\n"):
        return "image/png"
    if head.startswith(b"\xff\xd8\xff"):
        return "image/jpeg"
    if head[:4] == b"RIFF" and head[8:12] == b"WEBP":
        return "image/webp"
    if head.startswith(b"%PDF"):
        return "application/pdf"
    if head.startswith(b"%!PS") or head.startswith(b"\xc5\xd0\xd3\xc6"):   # PostScript / binary EPS
        return "application/postscript"
    text = head.lstrip(b"\xef\xbb\xbf \t\r\n").lower()
    if text.startswith(b"<svg") or (text.startswith(b"<?xml") and b"<svg" in data[:4096].lower()):
        return "image/svg+xml"
    return None


class FileStore(Protocol):
    def save(self, data: bytes, extension: str) -> str: ...      # returns a storage key
    def load(self, key: str) -> bytes: ...


class LocalFileStore:
    def __init__(self, base_dir: str):
        self.base = Path(base_dir).resolve()
        self.base.mkdir(parents=True, exist_ok=True)

    def save(self, data: bytes, extension: str) -> str:
        key = f"{uuid.uuid4().hex}.{extension}"
        (self.base / key).write_bytes(data)
        return key

    def load(self, key: str) -> bytes:
        path = (self.base / key).resolve()
        if path.parent != self.base:          # keys are generated by us; never follow anything else
            raise FileNotFoundError(key)
        return path.read_bytes()
